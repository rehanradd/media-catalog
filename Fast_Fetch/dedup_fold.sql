SELECT e.id AS old_episode_id, e2.id AS new_episode_id
FROM cat_episodes e
JOIN _fold_season_map m ON m.old_season_id = e.season_id
JOIN cat_episodes e2 ON e2.season_id = m.new_season_id
    AND e2.number = e.number;
